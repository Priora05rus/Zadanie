#include <iostream>       // подключаем библиотеку для ввода-вывода
#include <cmath>          // подключаем библиотеку математических функций (например, sin, fabs)
#include <iomanip>        // подключаем для форматирования вывода (setprecision, setw)

using namespace std;      // используем пространство имён std, чтобы не писать std:: перед cout и др.

/// Функция вычисляет значение y по формуле y = x - 1 / (3 + sin(3.6x))
double func(double x) {
    double denominator = 3 + sin(3.6 * x);   // считаем знаменатель выражения
    if (fabs(denominator) < 1e-8) {          // если он близок к 0 (учёт ошибок округления)
        throw runtime_error("деление на ноль"); // выбрасываем исключение, если деление невозможно
    }
    return x - 1.0 / denominator;            // вычисляем и возвращаем результат
}

int main() {
    double start = 0.0;      // начальное значение интервала x
    double end = 0.85;       // конечное значение интервала x
    double step = 0.05;      // шаг изменения x (Δx)

    cout << fixed << setprecision(4);     // устанавливаем формат вывода чисел: фиксированная точка, 4 знака после запятой
    cout << " x\t\t y" << endl;           // заголовок таблицы
    cout << "------------------------" << endl; // разделительная линия

    // цикл от x = start до x <= end (включительно), шаг — 0.05
    for (double x = start; x <= end + 1e-9; x += step) {
        cout << setw(5) << x << "\t";     // печатаем значение x с шириной 5 символов

        try {
            double y = func(x);           // вызываем функцию и получаем y
            cout << setw(10) << y << endl; // печатаем y с шириной 10 символов
        } catch (const exception& e) {
            // если в функции произошло исключение — печатаем сообщение
            cout << "  нет решения (" << e.what() << ")" << endl;
        }
    }

    return 0;  // завершение программы
}